import assert from 'node:assert/strict';
import {evaluateStockStrategyFork} from '../src/crypto/bot/stock/setup/botStockStrategyFork.js';
import {adaptAlpacaBarsToStockSetup} from '../src/crypto/bot/stock/setup/botStockMarketAdapter.js';
const asOf=Date.parse('2026-10-21T20:00:00Z');
const bars=Array.from({length:100},(_,i)=>{
  const close=100+Math.sin(i/5)*2+i*.04;
  return {timestamp:new Date(asOf-(101-i)*300000).toISOString(),open:close-.15,high:close+.55,low:close-.65,close,volume:100000+i*500};
});
const market=adaptAlpacaBarsToStockSetup({symbol:'AAPL',bars,timeframe:'5Min',asOf});
assert.equal(market.instrumentType,'EQUITY');
assert.equal(market.candles.length,100);
assert.equal(market.spreadPercent,null);
assert.equal(market.slippage,null);
const r=evaluateStockStrategyFork({symbol:'AAPL',bars,timeframe:'5Min',direction:'BULL',asOf});
assert.equal(r.assetClass,'STOCK');
assert.equal(r.researchOnly,true);
assert.equal(r.executionAuthority,false);
assert.equal(r.liveExecution,false);
assert.ok(r.setup?.structure);
assert.ok(r.setup?.regime);
assert.ok(r.setup?.strategySelection);
assert.ok(r.setup?.quality);
assert.notEqual(r.setup?.instrumentType,'PERPETUAL');
assert.equal(r.setup?.setupType==='BUY'||r.setup?.setupType==='SELL',false);
assert.throws(()=>evaluateStockStrategyFork({symbol:'AAPL',bars,direction:'NONE',asOf}),/DIRECTION_REQUIRED/);
const incomplete=adaptAlpacaBarsToStockSetup({symbol:'AAPL',bars:bars.slice(0,5),asOf});
assert.equal(incomplete.approved,false);
assert.ok(incomplete.blockers.includes('INSUFFICIENT_CLOSED_STOCK_BARS'));
const withOpen=[...bars,{timestamp:new Date(asOf-120000).toISOString(),open:105,high:106,low:104,close:105.5,volume:1000}];
assert.equal(adaptAlpacaBarsToStockSetup({symbol:'AAPL',bars:withOpen,asOf}).candles.length,100);
console.log('PASS: independent stock strategy fork, 5-strategy pipeline, OHLCV adapter, closed bars, research-only');
