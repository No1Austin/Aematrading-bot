import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {inspectArchive,inspectSetup,summarizeSetups} from '../src/crypto/bot/quant/quantArchiveResearchReport.js';
import {buildReadinessReport} from './emaQuantResearchReadiness.js';
const payload={timestamp:'2026-10-18T20:00:00.000Z',market:{symbol:'ETH_USDT'},candleInterval:'5m',pointInTimeVerified:false,archiveMetadata:{capturedAt:'2026-10-18T20:00:00.000Z'}};
const hash=crypto.createHash('sha256').update(JSON.stringify(payload)).digest('hex');
payload.archiveMetadata.sha256=hash;
const text=JSON.stringify(payload)+'\n';
assert.equal(inspectArchive(text).hashMismatches,0);
assert.equal(inspectArchive(text).unverified,1);
assert.equal(inspectArchive(text+text).duplicates,1);
assert.equal(inspectArchive(text.replace('ETH_USDT','BTC_USDT')).hashMismatches,1);
const short={symbol:'TIA_USDT',direction:'BEAR',strategy:'BREAKOUT_RETEST',entry:0.5984,stop:0.5986482142857142,target:0.5945,setupApproved:true};
const s=inspectSetup(short,{costBps:12});
assert.equal(s.geometryValid,true);
assert.ok(s.breakEvenTargetProbability>0 && s.breakEvenTargetProbability<1);
assert.equal(s.netExpectedR,null);
assert.equal(inspectSetup({...short,stop:0.59}).geometryValid,false);
assert.equal(summarizeSetups([short]).byStrategy.BREAKOUT_RETEST.total,1);
const report=buildReadinessReport({archiveText:text,diagnostic:{quantSetupShadow:[short]}});
assert.equal(report.trainingReady,false);
assert.equal(report.setups.total,1);
console.log('EMA quant research readiness tests passed');
