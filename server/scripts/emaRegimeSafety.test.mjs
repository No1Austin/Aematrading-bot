import assert from 'node:assert/strict';
import classify from '../src/crypto/bot/setup/botMarketRegimeEngine.js';
const candidate = {directionDecision:{direction:'LONG'}};
const base = {approved:true,trend:'BULLISH',structurePattern:'HH_HL',volatility:{regime:'NORMAL'},breakout:{detected:false},liquiditySweep:{detected:false},range:{low:90,high:110,midpoint:100}};
const trend = classify(candidate,base);
assert.equal(trend.approved,true);
assert.ok(trend.eligibleStrategies.includes('TREND_PULLBACK'));
assert.ok(trend.eligibilityDiagnostics.skippedStrategies.includes('RANGE_ROTATION'));
const expansion = classify(candidate,{...base,volatility:{regime:'EXPANDING'},breakout:{detected:true,direction:'LONG',displacementAtr:1},volume:{available:true,ratio:1.5}});
assert.ok(expansion.eligibleStrategies.includes('MOMENTUM_BREAKOUT'));
const blocked = classify(candidate,{...base,approved:false});
assert.equal(blocked.approved,false);
assert.deepEqual(blocked.eligibleStrategies,[]);
const invalidDirection = classify({directionDecision:{direction:'SIDEWAYS'}},base);
assert.equal(invalidDirection.approved,false);
assert.deepEqual(invalidDirection.eligibleStrategies,[]);
const range = classify({directionDecision:{direction:'BEAR'}},{approved:true,trend:'NEUTRAL',structurePattern:'SIDEWAYS',volatility:{regime:'NORMAL'},breakout:{detected:false},liquiditySweep:{detected:false},range:{low:90,high:110,midpoint:100}});
assert.ok(range.eligibleStrategies.includes('RANGE_ROTATION'));
console.log('5 regime safety scenarios passed');
