import assert from 'node:assert/strict';
import {normalizeDiscoverySymbols,rankStockCandidates,discoverStockCandidates} from '../src/crypto/bot/stock/botStockDiscoveryEngine.js';
const now=Date.parse('2026-10-19T20:00:00Z');
const makeBars=(volume=10000,step=.1)=>Array.from({length:90},(_,i)=>({timestamp:new Date(now-(89-i)*300000).toISOString(),open:100+i*step,high:101+i*step,low:99+i*step,close:100.5+i*step,volume}));
assert.deepEqual(normalizeDiscoverySymbols([' aapl ','AAPL','msft']),['AAPL','MSFT']);
assert.throws(()=>normalizeDiscoverySymbols(['AAPL/../../']),/INVALID/);
const ranked=rankStockCandidates({symbols:['AAPL','MSFT','BAD'],barsBySymbol:{AAPL:makeBars(20000),MSFT:makeBars(10000),BAD:[]},asOf:now,minAverageDollarVolume:1000});
assert.equal(ranked.candidates.length,2);
assert.equal(ranked.rejected.find(x=>x.symbol==='BAD').reasons[0],'INSUFFICIENT_BARS');
const fetchBatch=async ({symbols})=>({approved:true,barsBySymbol:Object.fromEntries(symbols.map(s=>[s,makeBars(s==='AAPL'?20000:10000)])),warnings:[]});
const result=await discoverStockCandidates({symbols:['AAPL','MSFT'],asOf:now,fetchBatch,minAverageDollarVolume:1000});
assert.equal(result.scanned,2);
assert.equal(result.candidates.length,2);
assert.equal(result.researchOnly,true);
assert.equal(result.liveExecution,false);
const truncated=await discoverStockCandidates({symbols:['AAPL'],asOf:now,fetchBatch:async()=>({approved:true,warnings:['Historical batch download reached the configured 600-bar safety limit.'],barsBySymbol:{AAPL:makeBars()}})});
assert.equal(truncated.candidates.length,0);
assert.equal(truncated.providerErrors[0].errors[0],'BATCH_TRUNCATED_AT_SAFETY_LIMIT');
console.log('PASS: discovery ranking, invalid symbols, batch scanning, truncation safety, research-only');
